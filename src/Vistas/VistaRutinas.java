    private void btnActualizarRutinaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarRutinaActionPerformed
        // Verificar que se haya seleccionado un ejercicio
    if (idRutinaSeleccionada == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Primero debe seleccionar un ejercicio de la tabla.",
                "Ejercicio no seleccionado",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Validar los campos obligatorios
    if (txtNombreEjercicio.getText().trim().isEmpty()
            || txtDescripcion.getText().trim().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Debe completar el nombre y la descripción del ejercicio.",
                "Campos incompletos",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Recuperar el estado actual del ejercicio
    Rutina rutinaActual = rutinaData.buscarRutina(idRutinaSeleccionada);

    if (rutinaActual == null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No se encontró el ejercicio seleccionado."
        );

        return;
    }

    // Obtener los datos modificados del formulario
    String nombre = txtNombreEjercicio.getText().trim();
    String grupo = cbGrupoMuscular.getSelectedItem().toString();
    String descripcion = txtDescripcion.getText().trim();

    String ruta = txtRutaAnimacion.getText().trim();

    if (ruta.isEmpty()) {
        ruta = null;
    }

    // Crear el objeto con los datos actualizados
    Rutina rutina = new Rutina(
            nombre,
            grupo,
            descripcion,
            ruta,
            rutinaActual.isEstado()
    );

    // Asignar el ID del ejercicio seleccionado
    rutina.setIdRutina(idRutinaSeleccionada);

    // Actualizar el registro en la base de datos
    rutinaData.actualizarRutina(rutina);

    // Actualizar la tabla y limpiar el formulario
    cargarTablaRutinas();
    limpiarCamposRutina();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "El ejercicio se actualizó correctamente."
    );
    }//GEN-LAST:event_btnActualizarRutinaActionPerformed

