   private void mostrarAnimacionEjercicio(Rutina rutina) {

    if (rutina != null
            && rutina.getRutaAnimacion() != null
            && !rutina.getRutaAnimacion().isBlank()) {

        try {
            java.net.URL recurso = getClass().getResource(
                    rutina.getRutaAnimacion()
            );

            if (recurso != null) {
                lblAnimacionRutina.setIcon(
                        new javax.swing.ImageIcon(recurso)
                );
                lblAnimacionRutina.setText("");

            } else {
                lblAnimacionRutina.setIcon(
                        new javax.swing.ImageIcon(
                                rutina.getRutaAnimacion()
                        )
                );
                lblAnimacionRutina.setText("");
            }

        } catch (Exception e) {
            lblAnimacionRutina.setIcon(null);
            lblAnimacionRutina.setText(
                    "No se pudo cargar la animación"
            );
        }

    } else {
        lblAnimacionRutina.setIcon(null);
        lblAnimacionRutina.setText(
                "Este ejercicio no tiene animación"
        );
    }
} 
 
private void cargarTablaRutinas() {

    DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"ID", "Ejercicio", "Grupo muscular", "Estado"}, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    // Obtener el grupo muscular seleccionado en el filtro
    String filtro = cbFiltroGrupoMuscular.getSelectedItem().toString();

    // Recuperar todos los ejercicios de la base de datos
    List<Rutina> listaRutinas = rutinaData.listarRutinas();

    // Recorrer los ejercicios y aplicar el filtro
    for (Rutina rutina : listaRutinas) {

        if (filtro.equals("Todos")
                || rutina.getGrupoMuscular().equalsIgnoreCase(filtro)) {

            Object[] fila = {
                rutina.getIdRutina(),
                rutina.getNombreEjercicio(),
                rutina.getGrupoMuscular(),
                rutina.isEstado() ? "Activo" : "Inactivo"
            };

            modelo.addRow(fila);
        }
    }

    // Mostrar los resultados en la tabla
    jTableRutinas.setModel(modelo);
}
  

