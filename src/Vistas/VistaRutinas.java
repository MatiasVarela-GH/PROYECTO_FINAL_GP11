    private void btnAltaRutinaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAltaRutinaActionPerformed
      // Verificar que se haya seleccionado un ejercicio
    if (idRutinaSeleccionada == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Primero debe seleccionar un ejercicio de la tabla.",
                "Ejercicio no seleccionado",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Buscar el ejercicio seleccionado
    Rutina rutina = rutinaData.buscarRutina(idRutinaSeleccionada);

    if (rutina == null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No se encontró el ejercicio seleccionado."
        );

        return;
    }

    // Verificar si ya está activo
    if (rutina.isEstado()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Este ejercicio ya se encuentra activo."
        );

        return;
    }

    // Confirmar el alta
    int respuesta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de que desea dar de alta este ejercicio?",
            "Confirmar alta",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.QUESTION_MESSAGE
    );

    if (respuesta == javax.swing.JOptionPane.YES_OPTION) {

        // Activar el ejercicio
        rutinaData.activarRutina(idRutinaSeleccionada);

        // Actualizar la tabla
        cargarTablaRutinas();

        // Limpiar el formulario
        limpiarCamposRutina();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "El ejercicio fue dado de alta correctamente."
        );
    }  
    }//GEN-LAST:event_btnAltaRutinaActionPerformed

    private void btnGuardarRutinaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarRutinaActionPerformed
     

    // Validamos que los campos obligatorios no estén vacíos
    if (txtNombreEjercicio.getText().trim().isEmpty()
            || txtDescripcion.getText().trim().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Debe completar el nombre y la descripción del ejercicio.",
                "Campos incompletos",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Obtenemos los datos del formulario
    String nombre = txtNombreEjercicio.getText().trim();
    String grupo = cbGrupoMuscular.getSelectedItem().toString();
    String descripcion = txtDescripcion.getText().trim();

    String ruta = txtRutaAnimacion.getText().trim();

    // Si no se ingresó una ruta, guardamos NULL
    if (ruta.isEmpty()) {
        ruta = null;
    }

    // Creamos el objeto Rutina
    Rutina rutina = new Rutina(
            nombre,
            grupo,
            descripcion,
            ruta,
            true
    );

    // Guardamos el ejercicio en la base de datos
    rutinaData.guardarRutina(rutina);

    // Actualizamos la tabla
    cargarTablaRutinas();

    // Limpiamos el formulario
    limpiarCamposRutina();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "El ejercicio se guardó correctamente."
    );

    }//GEN-LAST:event_btnGuardarRutinaActionPerformed

